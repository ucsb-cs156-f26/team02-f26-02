import { createElement } from "react";
import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { MemoryRouter } from "react-router";
import UCSBDiningCommonsMenuItemForm from "main/components/UCSBDiningCommonsMenuItem/UCSBDiningCommonsMenuItemForm";
import { ucsbDiningCommonsMenuItemFixtures } from "fixtures/ucsbDiningCommonsMenuItemFixtures";

const mockedNavigate = vi.fn();
vi.mock("react-router", async () => {
  const originalModule = await vi.importActual("react-router");
  return { ...originalModule, useNavigate: () => mockedNavigate };
});

function renderForm(props = {}) {
  return render(
    createElement(
      MemoryRouter,
      null,
      createElement(UCSBDiningCommonsMenuItemForm, props),
    ),
  );
}

describe("UCSBDiningCommonsMenuItemForm tests", () => {
  test("uses a custom submit button label", () => {
    renderForm({ buttonLabel: "Update" });
    expect(screen.getByRole("button", { name: "Update" })).toBeInTheDocument();
    expect(
      screen.queryByRole("button", { name: "Create" }),
    ).not.toBeInTheDocument();
  });

  test("navigates back when Cancel is clicked without submitting", () => {
    const submitAction = vi.fn();
    mockedNavigate.mockClear();
    renderForm({ submitAction });
    fireEvent.click(screen.getByRole("button", { name: "Cancel" }));
    expect(mockedNavigate).toHaveBeenCalledWith(-1);
    expect(submitAction).not.toHaveBeenCalled();
  });

  const fields = [
    ["diningCommonsCode", "Dining Commons Code"],
    ["name", "Name"],
    ["station", "Station"],
  ];

  test("hides the autogenerated ID and starts empty without initialContents", () => {
    renderForm({ submitAction: vi.fn() });

    expect(
      screen.queryByTestId("UCSBDiningCommonsMenuItemForm-id"),
    ).not.toBeInTheDocument();
    fields.forEach(([field]) => {
      expect(
        screen.getByTestId(`UCSBDiningCommonsMenuItemForm-${field}`),
      ).toHaveValue("");
    });
    expect(screen.getByRole("button", { name: "Create" })).toBeInTheDocument();
  });

  test.each([
    ["", "is required."],
    ["   ", "must not be blank."],
    ["a".repeat(256), "must be at most 255 characters."],
  ])("rejects invalid field values: %j", async (value, message) => {
    const submitAction = vi.fn();
    renderForm({ submitAction });

    fields.forEach(([field]) => {
      fireEvent.change(
        screen.getByTestId(`UCSBDiningCommonsMenuItemForm-${field}`),
        { target: { value } },
      );
    });
    fireEvent.click(screen.getByRole("button", { name: "Create" }));

    for (const [, label] of fields) {
      expect(
        await screen.findByText(`${label} ${message}`),
      ).toBeInTheDocument();
    }
    expect(submitAction).not.toHaveBeenCalled();
  });

  test("accepts fixture values and the 255-character boundary", async () => {
    const submitAction = vi.fn();
    const initialContents = ucsbDiningCommonsMenuItemFixtures.oneMenuItem;
    const { unmount } = renderForm({ initialContents, submitAction });
    expect(screen.getByLabelText("Id")).toHaveValue(String(initialContents.id));
    expect(screen.getByLabelText("Id")).toHaveAttribute("readonly");
    fields.forEach(([field]) => {
      expect(
        screen.getByTestId(`UCSBDiningCommonsMenuItemForm-${field}`),
      ).toHaveValue(initialContents[field]);
    });
    fireEvent.click(screen.getByRole("button", { name: "Create" }));
    await waitFor(() => expect(submitAction).toHaveBeenCalledTimes(1));
    expect(submitAction.mock.calls[0][0]).toMatchObject({
      id: initialContents.id,
      diningCommonsCode: initialContents.diningCommonsCode,
      name: initialContents.name,
      station: initialContents.station,
    });
    unmount();

    renderForm({ submitAction });
    fields.forEach(([field]) => {
      fireEvent.change(
        screen.getByTestId(`UCSBDiningCommonsMenuItemForm-${field}`),
        { target: { value: "a".repeat(255) } },
      );
    });
    fireEvent.click(screen.getByRole("button", { name: "Create" }));
    await waitFor(() => expect(submitAction).toHaveBeenCalledTimes(2));
  });
});
